/// Pointer to the server-stored plugin CODE (Faz-4 server-code; `PLUGIN_FEED_LOG_SPEC §blob`).
/// A plugin's html/bundle is no longer carried INLINE on the wire (the 64KB envelope pain, and
/// a huge web app was outright impossible) → it lives ENCRYPTED in a durable, group-gated R2
/// blob on the server (the server is BLIND). This pointer is carried both in the live
/// `PluginInstall` fan-out and in the server-log install registry (the same manifest) → the
/// receiver downloads the code, verifies its integrity, decrypts it and caches it.
///
/// **The key is INDEPENDENT of the epoch:** the code is immutable and owns its own random
/// key; even when a member leaving rotates the epoch (the data key changes), an old device can
/// still decrypt the code. The key travels inside E2E (a wire protected by Olm or the epoch
/// key) → the server never SEES it; the ciphertext in R2 is opaque without the key.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PluginCodeRefV1 {
    /// Durable blob id on the server (`/plugin-blob/<room>/<blob_id>`). Gated on group membership.
    pub blob_id: String,
    /// BLAKE3(ciphertext) in base64 — content address + post-download integrity. A malicious
    /// server cannot serve corrupt or substituted bytes (the hash would not match); together
    /// with the XChaCha20-Poly1305 AEAD tag this is defense in depth.
    pub blob_hash_b64: String,
    /// BLAKE3(plaintext code) in base64 — post-decrypt verification plus the basis for
    /// re-consent on a code change (`code_hash != code_hash` instead of the old
    /// `html != html` comparison).
    pub code_hash_b64: String,
    /// Blob-specific random AEAD key (32B, base64). Taken from the manifest that
    /// `sezi_file::encrypt_in_memory` returns.
    pub key_b64: String,
    /// XChaCha20-Poly1305 STREAM nonce (19B, base64).
    pub nonce_b64: String,
    /// STREAM chunk size (needed for decryption; the same as `FileManifest.chunk_size`).
    pub chunk_size: u32,
    /// Plaintext code size — a pre-download guard and DoS limit.
    pub size: u64,
    /// Bundle entry file (for the huge-web FAZ-C; empty for single-file html). Forward-compat.
    #[serde(default)]
    pub entrypoint: String,
    /// Cipher scheme — forward compatibility (only one value for now).
    #[serde(default = "default_code_enc")]
    pub enc: String,
}

/// serde default for `PluginCodeRefV1.enc`.
fn default_code_enc() -> String {
    "xchacha20poly1305-stream".to_string()
}

/// Current schema version of the Sezgi wire format. v1 denotes the existing
/// JSON+Olm envelope format. v2+ changes (group chat / Megolm, a binary
/// envelope, ext field extensions) will bump this number later on.
///
/// As of today the sender always writes `WIRE_SCHEMA_VERSION`; the receiver
/// parses incoming messages with `default = 1` and does NOT (yet) reject a
/// higher version — it simply skips unknown fields silently (forward-compat).
pub const WIRE_SCHEMA_VERSION: u16 = 1;

pub(super) fn default_schema_version() -> u16 {
    WIRE_SCHEMA_VERSION
}

/// serde default for `PluginInstall.mode` — a message from an older sender (no field) counts
