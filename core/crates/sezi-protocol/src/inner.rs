/// data loss).
fn default_plugin_mode() -> String {
    "persistent".to_string()
}

pub(super) fn is_default_ext(v: &serde_json::Value) -> bool {
    v.is_null()
}

impl InnerMessage {
    pub fn encode(&self) -> Vec<u8> {
        serde_json::to_vec(self).expect("inner message serialize")
    }

    pub fn decode(bytes: &[u8]) -> Result<Self> {
        Ok(serde_json::from_slice(bytes)?)
    }

    /// Variants a device writes into its OWN database and that must never be accepted from the
    /// wire. Not a hint — the inbound paths reject these, because for both of them the local
    /// origin is the entire meaning:
    ///
    /// - `RoomAccessNotice` says "my membership reconciliation saw this person gain the ability
    ///   to read this room". Accepting one from a peer would turn a statement your device made
    ///   about what it did into somebody else's claim about who may read a room — and since the
    ///   notice exists precisely because group membership is NOT signed, a forgeable notice is
    ///   worse than none: it is a channel for manufacturing false reassurance, or for burying a
    ///   real join under noise.
    /// - `CallLog` is each endpoint's own record of a call from its own perspective. Without the
    ///   rejection a peer could post an arbitrary call-history row into a conversation. Same
    ///   class, same answer.
    ///
    /// - `CallRecordingNotice` is this device's record of a recording signal it received —
    ///   the same class as `RoomAccessNotice`, for the same reason.
    /// - `PluginAddedNotice` is this device's record of an install it applied; from a peer it
    ///   would let anyone announce an app nobody added.
    ///
    /// Note this is about the CONTENT paths. None of these variants is ever sent, so rejecting
    /// them costs nothing that any honest client does.
    pub fn is_local_only(&self) -> bool {
        matches!(
            self,
            InnerMessage::CallLog { .. }
                | InnerMessage::RoomAccessNotice { .. }
                | InnerMessage::CallRecordingNotice { .. }
                | InnerMessage::PluginAddedNotice { .. }
        )
    }

    /// Is this inner a GROUP-oriented control message? `true` → it must be fanned out to ALL
    /// active devices of the recipient USER (`SendGroupFanout`) and must NEVER go primary-only
    /// (`SendControl`) — otherwise the recipient's sibling device CANNOT receive the group key
    /// / the install / the snapshot / live group plugin data. Dispatch DERIVES its targeting
    /// from this method → even if a call site picks `SendControl` by mistake it is redirected
    /// to the fan-out. The call site cannot choose; that is the point.
    ///
    /// CLASSIFICATION:
    /// - Group session key + group lifecycle + epoch key + history snapshot → ALWAYS fan out.
    /// - Plugin data/install: only when `room: Some` (a group context) → fan out; `room: None`
    ///   means 1:1 → primary-only. An Activity fans out when its scope is a `Room`.
    /// - A file's download ack (`MediaReceived` / `P2pBlobReceived`) → fan out, 1:1 or not: the
    ///   device waiting for it is the one that SENT the file, which may be a linked one. Its
    ///   call sites send `SendGroupFanout`; listing it here redirects an ack row a build before
    ///   2026-10-15 queued as `SendControl`.
    /// - EXCLUDED (stay primary-only): REQUEST/PULL triggers (`*Request` — idempotent, the
    ///   requesting device simply asks again) + the self-state path
    ///   (`RoomKeyGossip`/`*OutboundCopy`/`DeviceState*`/`ReadSelfSync` — these already reach
    ///   my own devices via `SendSelfState`) + 1:1 content (`Text`/`File`/...) + call
    ///   signaling (`CallSignal` — a separate real-time domain).
    pub fn requires_device_fanout(&self) -> bool {
        matches!(
            self,
            InnerMessage::RoomKeyShare { .. }
                | InnerMessage::GroupReceipt { .. }
                | InnerMessage::GroupJoinAccepted { .. }
                | InnerMessage::GroupMembershipChanged { .. }
                | InnerMessage::PluginEpochKeyShare { .. }
                | InnerMessage::PluginRecordSnapshot { .. }
                | InnerMessage::PluginRemoved { .. }
                | InnerMessage::PluginRecord { room: Some(_), .. }
                | InnerMessage::Activity { scope: ActivityWireScope::Room { .. }, .. }
                | InnerMessage::PluginInstall { room: Some(_), .. }
                | InnerMessage::MediaReceived { .. }
                | InnerMessage::P2pBlobReceived { .. }
        ) || matches!(self, InnerMessage::ActivityBatch { events }
            if events.iter().any(|e| e.scope.room_id().is_some()))
    }

    /// Diagnostic label for the `requires_device_fanout` guard — PII-free, the variant name only.
    pub fn fanout_kind_label(&self) -> &'static str {
        match self {
            InnerMessage::RoomKeyShare { .. } => "RoomKeyShare",
            InnerMessage::GroupReceipt { .. } => "GroupReceipt",
            InnerMessage::GroupJoinAccepted { .. } => "GroupJoinAccepted",
            InnerMessage::GroupMembershipChanged { .. } => "GroupMembershipChanged",
            InnerMessage::PluginEpochKeyShare { .. } => "PluginEpochKeyShare",
            InnerMessage::PluginRecordSnapshot { .. } => "PluginRecordSnapshot",
            InnerMessage::PluginRemoved { .. } => "PluginRemoved",
            InnerMessage::PluginRecord { .. } => "PluginRecord",
            InnerMessage::Activity { .. } => "Activity",
            InnerMessage::ActivityBatch { .. } => "ActivityBatch",
            InnerMessage::PluginInstall { .. } => "PluginInstall",
            InnerMessage::MediaReceived { .. } => "MediaReceived",
            InnerMessage::P2pBlobReceived { .. } => "P2pBlobReceived",
            _ => "other",
        }
    }
}

