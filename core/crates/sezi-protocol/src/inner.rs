//! Inner message format carried inside an Olm session.
//!
//! WireEnvelope -> Olm decrypt -> bytes -> ChatPayload:
//!   - thread_id    : optional; None = the "general" thread
//!   - thread_title : optional; set on the first message or when the thread is renamed
//!   - InnerMessage : (flattened) the actual message — Text / File / FileGroup / RichText
//!
//! ChatPayload wraps InnerMessage with `#[serde(flatten)]`; at the JSON root level this
//!   becomes `{thread_id, thread_title, kind, ...inner fields}`. That way older clients
//! that do not know about `thread_id` parse the message as a plain InnerMessage and
//! silently drop the extra fields (forward compatibility).
//!
//! This whole structure stays under E2E encryption — the server cannot tell any field apart.

use serde::{Deserialize, Serialize};

use sezi_error::Result;

/// Everything a receiver needs to fetch and decrypt one attachment: where the ciphertext is
/// (`media_id` → `/media/<media_id>` on the server, or a P2P blob), and the XChaCha20 STREAM
/// key/nonce plus the chunk size to read it with. `size`, `content_type` and `filename` are what
/// the UI renders before the download finishes.
///
/// This is a WIRE type — it travels inside [`InnerMessage::File`] and [`InnerMessage::FileGroup`],
/// under E2E encryption, so the server never sees the key. It lives here rather than next to the
/// crypto that produces it in `file.rs`: `file` depends on `attach_progress`, i.e. tokio and a
/// global `CancellationToken` registry, and a protocol module must not inherit that. `file`
/// re-exports it.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FileManifest {
    pub v: u8,
    /// R2 object id on the server (`/media/<media_id>`).
    pub media_id: String,
    pub key_b64: String,
    pub nonce_b64: String,
    pub chunk_size: u32,
    pub size: u64,
    pub content_type: String,
    pub filename: String,
}

/// Upper size ceiling for an inbound message payload: keeps a malicious/modified client from
/// bloating the receiver's DB/memory with a huge `HtmlMessage`/`RichText`/opaque string. The
/// outbound side enforces ~16KB for `HtmlMessage`; this is the inbound counterpart. 256KB is far
/// above any normal message, so it cuts inflation while letting legitimate content through.
pub const MAX_INBOUND_PAYLOAD_BYTES: usize = 256 * 1024;

/// See `InnerMessage::Typing::active` — a missing flag means the sender is an older client, and
/// an older client only ever sent heartbeats.
fn typing_active_default() -> bool {
    true
}

/// Paired with the default above so a HEARTBEAT stays byte-identical to an older client's: the
/// field is written only when it is `false`. The common case — one frame every three seconds
/// while someone types — therefore costs nothing new on the wire.
fn is_true(b: &bool) -> bool {
    *b
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum InnerMessage {
    Text { body: String },
    File(FileManifest),
    /// 2+ attachments in a single message. Atomic semantics: either all of them are sent
    /// or none at all (one single Olm envelope). The UI renders these as a grid.
    FileGroup { manifests: Vec<FileManifest> },
    /// Rich text as Quill Delta JSON. `plain_text` is the fallback for a receiver on an
    /// older version, or for generating previews — it is produced on the sender side via
    /// Document.toPlainText().
    RichText {
        delta_json: String,
        plain_text: String,
    },
    /// Single-file HTML written/pasted by the user — rendered inside the receiver's chat
    /// BUBBLE in a locked-down WebView (network OFF + no `sezgi` bridge + no persistence).
    /// This is NOT a plugin: no durable shared data, no install/consent step; it is a
    /// "somewhat capable but transient" user-HTML card (animation/interaction is free
    /// inside, zero reach outside). Size is capped in the kernel (double base64 → ~16KB
    /// raw ceiling). An older receiver (`#[serde(other)] Unknown`) sees "unknown message
    /// type" — it does not crash.
    HtmlMessage { html: String },
    /// One-shot (snapshot) location share. latitude/longitude are WGS84.
    /// `label` is the user's optional caption (e.g. "I'm here"),
    /// `accuracy` is the GPS accuracy in meters.
    Location {
        latitude: f64,
        longitude: f64,
        #[serde(skip_serializing_if = "Option::is_none", default)]
        label: Option<String>,
        #[serde(skip_serializing_if = "Option::is_none", default)]
        accuracy: Option<f64>,
    },
    /// Web page preview generated by the sender. When a URL is shared the sender fetches
    /// the OpenGraph tags and embeds them into the message; the receiver performs no extra
    /// fetch (only if it taps through to the page). `body_text` is the text the user typed
    /// alongside the message (optional — empty when only a URL is shared).
    LinkPreview {
        url: String,
        #[serde(skip_serializing_if = "Option::is_none", default)]
        title: Option<String>,
        #[serde(skip_serializing_if = "Option::is_none", default)]
        description: Option<String>,
        #[serde(skip_serializing_if = "Option::is_none", default)]
        image_url: Option<String>,
        #[serde(skip_serializing_if = "Option::is_none", default)]
        body_text: Option<String>,
    },
    /// Plugin/SharedActivity envelope. Every co-presence feature (piano, drawing, chess,
    /// watching video/photos/music together) travels over this single variant — Olm
    /// protected, server blind. Details: feedback_plugin_architecture.
    ///
    /// `payload` is the plugin's own schema (carried as an opaque JSON string).
    /// `event` is typed: control events (Invite/Join/Leave) are handled in ChatRuntime for
    /// lifecycle management; Domain events are forwarded to the plugin. `seq` increases
    /// monotonically within a plugin — used to tell late-arriving / out-of-order events
    /// apart. `activity_id` ties all events of the same activity together (e.g. a single
    /// chess game).
    Activity {
        plugin_id: String,
        activity_id: String,
        seq: u64,
        event: ActivityEvent,
        payload: String,
        /// Where the session lives — required, see [`ActivityWireScope`]. `Room`: the receiver
        /// verifies the sender's membership and writes the invite/summary card into the GROUP
        /// conversation, not into the sender's 1:1. `author` is NOT on the wire — the kernel
        /// verifies `sender_id` (symmetric with PluginRecord).
        scope: ActivityWireScope,
        /// The sender reads [`InnerMessage::ActivityBatch`] — set on every event a current client
        /// sends, absent from an older one's (`activity_batch.rs`). Written only when true, so a
        /// receiver that does not know the field reads the event as it always has.
        #[serde(default, skip_serializing_if = "std::ops::Not::not")]
        reads_batch: bool,
    },
    /// Several [`InnerMessage::Activity`] events for one recipient in one envelope, in the order
    /// they were sent — sent only to a peer that said it reads them (`activity_batch.rs`).
    ActivityBatch { events: Vec<crate::activity_batch::ActivityBatchItem> },
    /// Local call-history record (shown in the chat bubble as "📞 Voice call · 2:34" /
    /// "Missed call"). NEVER GOES TO THE OTHER SIDE — each endpoint writes it from its own
    /// perspective (`direction` in/out + `status`) inside its own `_teardown`;
    /// `handle_log_call` inserts a LOCAL MessageRow and it is never sent via
    /// SendControl/Olm (if one arrives inbound it is ignored).
    /// `call_type`: "voice"|"video"; `status`: "completed"|"missed"|"declined"|"canceled".
    CallLog {
        call_type: String,
        duration_sec: u32,
        status: String,
    },
    /// Local room-access notice — "this member can read this room from now on".
    ///
    /// NEVER GOES TO THE OTHER SIDE, and that is the security property, not an optimization.
    /// Group membership is deliberately NOT signed (AGENTS.md, "Who the server owner is"), so the
    /// residue is answered by visibility — and visibility is only worth anything if it cannot be
    /// suppressed. A broadcast is exactly what a hostile relay drops. Instead every member's
    /// device writes its OWN copy, from its OWN reconciliation, on the same code path that
    /// releases its key: a device that gave out the key also wrote the notice, with no ordering
    /// in which one happens and the other does not.
    ///
    /// Written by `announce_room_access` (`kernel/groups_notice.rs`) as a local `MessageRow` with
    /// a DETERMINISTIC `local_id`, which is what makes it exactly-once. If one somehow arrives
    /// inbound it decodes to an invisible `control` row.
    ///
    /// `user_id`: whose access changed. `event`: `"joined"` (the only value emitted today —
    /// a string, like `CallLog.status`, so an older reader degrades to `Unknown` instead of
    /// failing to parse). The sentence is NOT built here: the core emits the code and the id,
    /// and the UI composes the localized sentence from them.
    RoomAccessNotice {
        user_id: String,
        event: String,
    },
    /// Local call-recording notice — "this member started / stopped recording the group's call".
    ///
    /// NEVER GOES TO THE OTHER SIDE, for the reason [`InnerMessage::RoomAccessNotice`] gives: every
    /// device writes its own row from its own receipt of the recorder's E2E `recording` signal
    /// (`kernel/call_recording.rs`), so a relay can neither forge one nor take back one already
    /// written. Accepting such a row from a peer would make "X recorded this lesson" somebody's
    /// claim instead of what this device heard.
    ///
    /// `user_id`: who records. `event`: `"started"` | `"stopped"` — a string, like
    /// `CallLog.status`, so an older reader degrades to `Unknown`. `duration_sec`: on `stopped`,
    /// how long the recording ran. The UI composes the sentence.
    CallRecordingNotice {
        user_id: String,
        event: String,
        #[serde(skip_serializing_if = "Option::is_none", default)]
        duration_sec: Option<u32>,
    },
    /// Local "an app was added to this group" notice — the chat row "Iris gruba eklendi · Aç"
    /// (board R7-WebApps-Intro, frame 9).
    ///
    /// NEVER GOES TO THE OTHER SIDE, for the reason [`InnerMessage::RoomAccessNotice`] gives: each
    /// device writes its own row from the install IT received and accepted through the admin-role
    /// gate (`kernel/plugin_notice.rs`), so a peer cannot post "an app was added" into a room.
    ///
    /// `plugin_id`/`name`/`icon` are the install's own, `added_by` the admin whose install this
    /// device applied. The sentence is not built here; the UI words it (a built-in app's purpose
    /// line comes from the UI's own table, keyed by `plugin_id`).
    PluginAddedNotice {
        plugin_id: String,
        name: String,
        #[serde(default)]
        icon: String,
        added_by: String,
    },
    /// P2P blob offer — the sender is serving the raw bytes over iroh-blobs; this
    /// Olm-encrypted message carries only the **ticket + manifest** to the receiver. The
    /// receiver parses the ticket, calls `recv_blob` and pulls the bytes directly over
    /// QUIC (the server is not in the traffic path).
    ///
    /// `ticket` is the iroh `BlobTicket` string format (NodeId + hash + relay info).
    /// `manifest` is the same `FileManifest` used elsewhere — it carries the key/nonce, and
    /// the receiver decrypts with it after downloading (two-layer E2E: Olm for this message
    /// + the manifest key for the blob content).
    ///
    /// Going forward, the P2P fallback for attachment/file kinds runs over this variant.
    /// The existing `File`/`FileGroup` (R2 store-and-forward) path stays in parallel —
    /// `shouldUseP2P(kind)` is the runtime decision.
    P2pBlobOffer {
        ticket: String,
        manifest: FileManifest,
    },
    /// P2P blob-received ack — the receiver sends this Olm-encrypted to the sender once
    /// `recv_blob` finishes successfully. When the sender sees it, it moves the matching
    /// outgoing attachment from the `awaitingPeer` phase to `delivered`.
    ///
    /// `ticket_hash` is there to match WHICH blob was received — the sender keeps the
    /// `p2pTicket` BlobTicket string on its outgoing attachments, and the receiver takes
    /// the BLAKE3 hash of that same string and sends it. We do not send the whole ticket:
    /// both for size and for privacy (it is wrapped in Olm, but it is still a needlessly
    /// large string).
    P2pBlobReceived {
        ticket_hash: String,
        /// FORWARD-COMPAT: device id of the receiver that PRODUCED this ack. Currently
        /// UNUSED — with a single-device giver the correlation is implicitly correct; the
        /// field reserves room for group-P2P giver-device correlation without an atomic
        /// deploy. Older messages parse as `None` (`default`), and the single-device wire
        /// output is UNCHANGED (`skip_serializing_if`). Same pattern as `PluginRecord.room`.
        #[serde(skip_serializing_if = "Option::is_none", default)]
        device: Option<String>,
    },
    /// CF blob-received ack — the receiver sends this Olm-encrypted to the sender after the
    /// CF branch of `downloadAttachment` has finished decrypting and writing to disk. When
    /// the sender sees it, it moves the matching outgoing CF attachment from the `ready`
    /// phase to `delivered` (blue third tick).
    ///
    /// `media_id` is there to match WHICH blob was received — the sender stores `mediaId`
    /// on its outgoing attachments.
    ///
    /// Same purpose as `P2pBlobReceived`, different transport (CF R2 vs iroh QUIC). Two
    /// separate variants are kept because the sender's match key differs (ticket_hash vs
    /// media_id) and their future evolution is independent of each other.
    MediaReceived {
        media_id: String,
    },
    /// Group (Megolm) session key share (Faz 4). The sender delivers the initial
    /// `session_key` of the `GroupSession` it has just created (or rotated) for a room to
    /// every member over a SEPARATE 1:1 Olm session (NOT a fan-out — pairwise, so the key
    /// only ever reaches members and the server stays blind). The receiver builds an
    /// `InboundGroupSession` via `import_inbound_group_session` and writes it into
    /// `inbound_group_sessions` keyed by (room, sender, session_id) → it can now decrypt
    /// that sender's group messages.
    ///
    /// Invisible control message (NO UI message row) — carried over the `SendControl` path
    /// like `MediaReceived`/`P2pBlobReceived`; it advances the ratchet.
    /// `room_id` says which group, `session_id` is the Megolm session id (inbound matching),
    /// `session_key_b64` is the initial key to import.
    RoomKeyShare {
        room_id: String,
        session_id: String,
        session_key_b64: String,
    },
    /// P1 (crypto self-heal): RECEIVER-DRIVEN group key re-request. If a receiver cannot
    /// decrypt a group message from a sender (B) — no inbound session / lost key, i.e. the
    /// RoomKeyShare never arrived or was lost — it sends this to B over 1:1 Olm
    /// `SendControl` → B re-distributes the CURRENT room key via
    /// `distribute_room_key_to(requester)`. Active recovery instead of passive waiting
    /// (self-heal without a reset). `room_id` says which group.
    /// Invisible control (NO UI row). Receiver-side GUARD: only answer a requester that is
    /// an active member, plus a per-(room,sender) debounce. An older client sees `Unknown`
    /// (forward compatibility). `session_id` (G5): the EXACT Megolm session id being asked
    /// for — the other side can (in the future) distribute precisely that session; today it
    /// distributes its current outbound one. `#[serde(default)]` covers older clients.
    RoomKeyRequest {
        room_id: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        session_id: Option<String>,
    },
    /// M-1b (group multi-device GOSSIP): I FORWARD a `RoomKeyShare` I received from a
    /// MEMBER (A) over 1:1 Olm to MY OWN sibling devices → my sibling can then decrypt A's
    /// group ciphertext as well (the worker already fans A's message out to ALL devices of
    /// my account, so the sibling ALREADY gets it; the only missing piece is A's KEY).
    ///
    /// The DIFFERENCE from `RoomKeyShare` is `origin_user_id`: the receiving sibling
    /// imports the key NOT under the CARRIER (me) but under the ORIGIN (A) → it writes it
    /// via `import_room_key` keyed by (room, ORIGIN, session_id). Otherwise A's ciphertext
    /// would be looked up under "B's key" → undecryptable (Codex Q2 FATAL fix). Carried
    /// over self-Olm (`SendSelfState`) → fail-closed (the receiver only processes it when
    /// sender==my_user). IMPORT-ONLY: the receiver does NOT re-gossip it (the B1↔B2
    /// infinite-loop guard is the wire TYPE itself; RoomKeyShare=import+gossip,
    /// RoomKeyGossip=import only). `origin_device_id` is for attribution / M-6 anomaly
    /// detection (NOT a storage key — storage is keyed per user). An older client falls back
    /// to `Unknown` (forward compatibility).
    RoomKeyGossip {
        origin_user_id: String,
        origin_device_id: String,
        room_id: String,
        session_id: String,
        session_key_b64: String,
    },
    /// Group message DELIVERED/READ receipt (Faz 6 #1). A group member sends the `msg_uid`s
    /// of the group messages it has RECEIVED (`read=false`) or READ (`read=true`) to the
    /// ORIGINAL SENDER over 1:1 Olm (NOT a fan-out — only to the sender).
    /// The sender collects the per-member receipts → all-delivered = second tick,
    /// all-read = blue.
    ///
    /// Invisible control (NO UI row) — the `MediaReceived` pattern; it advances the ratchet.
    /// `msg_uid` = the sender's message `local_id`; it is carried in the group's
    /// `ChatPayload.msg_uid` (inside E2E → every member sees the same id, and the sender
    /// matches its own message via `find_by_local_id`). `msg_uids` is batched (a read can
    /// combine several messages into a single receipt). THE SERVER IS UNCHANGED — this uses
    /// the existing 1:1 SendControl path.
    GroupReceipt {
        room_id: String,
        msg_uids: Vec<String>,
        read: bool,
    },
    /// Group-invite ACCEPTED notification (Faz 6 #3). AFTER the invitee `accept`s on the
    /// server, it sends this over 1:1 Olm to the member that added it (`added_by`) → that
    /// member distributes the group session key to the accepter (`distribute_room_key_to`)
    /// — E2E: the key only flows after acceptance — and marks the member 'active' locally.
    /// Invisible control (NO UI row) — the `RoomKeyShare` pattern.
    GroupJoinAccepted {
        room_id: String,
    },
    /// Group MEMBERSHIP-CHANGED notification (Faz 6 — leave/remove propagation). When a
    /// member leaves or is removed from a group, the leaver/remover sends this over 1:1 Olm
    /// to the REMAINING members → the receiving side REFRESHES the group
    /// (`handle_refresh_groups`): the member list is updated and reconciliation notices the
    /// missing member and rotates the outbound session.
    /// Invisible control (NO UI row) — the `GroupJoinAccepted` pattern. No sensitive data.
    GroupMembershipChanged {
        room_id: String,
    },
    /// Per-pair STATE DIGEST (invisible control) — the real fix for the fragility of the
    /// second tick (targeted reconciliation of Delivered/Read forwards that were silently
    /// dropped along the multi-hop ack chain). On EnterChat and on reconnect I send this
    /// peer a summary of "what I have received from you":
    ///   - `delivered_upto` = the highest `msg_id` I have RECEIVED from you (FIFO →
    ///     every message below it also reached me).
    ///   - `read_upto`      = the highest `msg_id` I have READ (viewed).
    /// The other side compares its own OUTGOING messages against its DB → and repairs the
    /// gap (a stuck Sent→Delivered, a missed →Read). NOT per message but on a natural event
    /// (opening a chat / reconnecting) → it does not tax the connection; one single
    /// mechanism.
    ///
    /// Two-way heal: the side receiving `reply=false` (a poke/request) first repairs its own
    /// outgoing state and THEN sends its own digest back with `reply=true` (so the
    /// requester heals too). A `reply=true` digest does NOT trigger a further response →
    /// no ping-pong (a reply flag instead of session-level dedup).
    ///
    /// Invisible (NO UI row) — the `RoomKeyShare`/`MediaReceived` pattern; advances the
    /// ratchet. An older client does not know the tag → it falls into `Unknown` (it acks and
    /// harmlessly swallows it).
    StateDigest {
        delivered_upto: i64,
        read_upto: i64,
        reply: bool,
    },
    /// Voice/video call signaling (calls epic, Faz 0). Invisible control
    /// (NO UI row) — the `RoomKeyShare`/`StateDigest` pattern; carried over Olm (1:1) and
    /// later Megolm (group). To the kernel, `data` is **OPAQUE**: the SDP offer/answer or
    /// ICE candidate JSON is produced/consumed by flutter_webrtc; the kernel only tracks
    /// call state via `signal_type` and routes the signal to the other side.
    ///
    /// `signal_type`: `invite` | `answer` | `ice` | `reject` | `end`
    /// (later, for groups: `join` | `leave`). `call_id` ties all signals of one call
    /// together (a UUID generated by the initiator). On the receiving side the sender is
    /// known from `sender_id` (no `from` is carried on the wire).
    CallSignal {
        call_id: String,
        signal_type: String,
        data: String,
    },
    /// "Typing…" indicator — EPHEMERAL presence. The sender emits it while typing in the
    /// conversation (~3s throttle); the receiver shows "X is typing" and AUTO-EXPIRES it
    /// after ~6s. NOT durable (no UI row, no persistence, no retry — the `CallSignal`
    /// ephemeral pattern: scope=None, best-effort, harmlessly dropped for an unreachable
    /// peer). `room`: `Some(gid)` → group conversation (the sender's membership is verified);
    /// `None` → 1:1 (the sender is the peer). Inbound → `DomainEvent::TypingChanged`. An older
    /// client falls back to `Unknown` (forward compatibility; it ignores it, harmless).
    ///
    /// The expiry is NOT redundant with `active: false`: a stop is one best-effort frame with no
    /// retry, so a lost one has to fall back on the timer. What the flag removes is the indicator
    /// standing for six seconds after someone types and then deletes without sending.
    Typing {
        #[serde(skip_serializing_if = "Option::is_none", default)]
        room: Option<String>,
        /// Send timestamp (epoch ms). The receiver filters out a STALE flush: because typing
        /// travels the E2E message path it gets recorded into the worker's `pending` and was
        /// delivered once, stale, by the flush on reopen ("typing shown wrongly on first
        /// open"). `now-ts > ~10s` → ignore. `default` → a Typing from an older client (no
        /// ts) has ts=0 → EXEMPT from the threshold check.
        #[serde(default)]
        ts: i64,
        /// `true` = started/still typing, `false` = stopped.
        ///
        /// **The default has to be `true`, and `#[serde(default)]` would give `false`.** A client
        /// built before this field sends no `active` at all, so the derived default would read
        /// every one of its heartbeats as a STOP and the indicator would never appear against an
        /// older peer. The other direction is safe on its own: the enum carries no
        /// `deny_unknown_fields`, so an older client ignores the flag and keeps its timer.
        #[serde(default = "typing_active_default", skip_serializing_if = "is_true")]
        active: bool,
    },
    /// Durable plugin-data record (HTML plugin platform, Dilim 2). A plugin's tree-shaped
    /// data (forum/list/wiki/announcement...) flows E2E over this variant using Megolm
    /// (group) or Olm (1:1) — the server is BLIND: both the content and the tree shape
    /// (`parent_id`) sit inside the encrypted envelope. Every device keeps a canonical
    /// replica (the `plugin_records` table) and converges via LWW: the highest `lamport`
    /// wins, ties broken by the sender's `sender_id` (kernel-verified and NOT carried on
    /// the wire → forged authorship is prevented). Invisible control (NO UI message row;
    /// the data lands in `plugin_records` and does not clutter the conversation).
    ///
    /// `op`: `put` (create/update) | `delete` (tombstone). `record_id` is the
    /// plugin-generated record id; `collection` is the logical group (e.g. "post").
    /// `fields_json` is the plugin's opaque schema. `lamport` is the sender's monotonic clock.
    PluginRecord {
        plugin_id: String,
        collection: String,
        record_id: String,
        #[serde(skip_serializing_if = "Option::is_none", default)]
        parent_id: Option<String>,
        op: String,
        fields_json: String,
        lamport: u64,
        /// Group (Room) context (GP1 — pairwise group plugin data). `Some(group_id)`
        /// → this record belongs to that group; the receiver writes `room_id = group_id`
        /// (all members plus the sender collect into the same logical collection).
        /// `None` → 1:1 (the receiver writes `room_id = sender_id`, the existing behavior).
        /// The group path is NOT Megolm: a SEPARATE 1:1 Olm `SendControl` per active member
        /// (the calls.rs group fan-out pattern; server blind, content E2E). `author` is NOT
        /// carried on the wire (the kernel verifies `sender_id`) → group author spoofing is
        /// structurally impossible.
        #[serde(skip_serializing_if = "Option::is_none", default)]
        room: Option<String>,
    },
    /// Portable plugin DISTRIBUTION (HTML plugin platform, Dilim 3a). One peer sends an
    /// HTML plugin (UI+logic as a single-file bundle) to another peer; the `html` BODY is
    /// carried directly on the wire, E2E over Olm (1:1) — the server is BLIND. The receiver
    /// writes it into `installed_plugins` as 'pending' (consent: "X sent you this plugin,
    /// install it?"); once the user accepts it becomes 'active' → it shows up in the picker
    /// and runs as a dynamic `HtmlPlugin` inside the locked-down WebView sandbox. Invisible
    /// control (NO UI message row; the invitation surfaces through `installed_plugins`; this
    /// variant flows over the same invisible `SendControl` path as `PluginRecord`).
    ///
    /// `icon` is a Material icon NAME (a string — `IconData` cannot be encoded on the wire,
    /// Dart maps it). `version` is monotonic (the basis for update / re-consent).
    PluginInstall {
        plugin_id: String,
        name: String,
        icon: String,
        /// LEGACY/cache: under the server-stored code model this arrives EMPTY on the wire
        /// (the code now comes down from the server via `code_ref`). The field is kept
        /// (serde default) → forward compatibility, and the locally decrypted code cache is
        /// held in the `installed_plugins.html` column.
        #[serde(default)]
        html: String,
        version: u32,
        /// Pointer to the server-stored plugin CODE (Faz-4 server-code). `Some` → the code
        /// sits encrypted in R2 and the receiver downloads and decrypts it (`html` is empty).
        /// `None` → (transitional/legacy) inline `html`.
        /// The live fan-out and the install registry carry the same manifest.
        #[serde(skip_serializing_if = "Option::is_none", default)]
        code_ref: Option<PluginCodeRefV1>,
        /// Plugin type: `"persistent"` (durable shared data + history sharing) | `"instant"`
        /// (live broadcast only, NO durable data). The receiver must know this so that
        /// snapshot/badge behavior is consistent on both devices. A message from an older
        /// sender does NOT carry the field → serde default `"persistent"` (backward
        /// compatibility: the safe side is the one that shares history).
        #[serde(default = "default_plugin_mode")]
        mode: String,
        /// Group (Room) context (v6 AUTHORITY MODEL). `Some(group_id)` → this plugin was
        /// assigned to that group by an ADMIN; the receiver writes `room_id = group_id` AND
        /// verifies the sender's owner/admin role in that group LOCALLY (`room_members` — not
        /// forgeable, server-synced). `None` → the old 1:1 distribution (DEPRECATED; the
        /// receiver rejects it — users can no longer distribute plugins, only an admin adds
        /// one to a group). Symmetric with `PluginRecord.room`. An older message does not
        /// carry the field → serde default None.
        #[serde(skip_serializing_if = "Option::is_none", default)]
        room: Option<String>,
        /// FAZ-A internet permission for a web plugin. `false` (DEFAULT, fail-closed) → the
        /// plugin's WebView is NETWORK-OFF with the sezgi bridge ON (bridged). `true` →
        /// NETWORK-ON with NO bridge (networked) — the single NETWORK-XOR-BRIDGE invariant
        /// (Dart `SandboxPolicy`). An older message does NOT carry the field → serde default
        /// `false` (the safe side: no permission = network off). MUTABLE (an admin can turn
        /// it on/off later); replay-guarded monotonically via `policy_rev`.
        #[serde(default)]
        web_enabled: bool,
        /// FAZ-A monotonic policy revision. +1 on every admin "internet on/off" change.
        /// Inbound replay guard: `incoming.policy_rev <= local` → IGNORE the `web_enabled`
        /// update (an old message cannot roll back a newer policy). An older message does NOT
        /// carry the field → default 0.
        #[serde(default)]
        policy_rev: u64,
    },
    /// GP3 history snapshot for a new member: a member that joins the group LATER receives
    /// ALL plugin records up to that moment (tombstones INCLUDED) in one shot → so the
    /// history from before it joined does not stay EMPTY. The adding member (`added_by`)
    /// builds it from its own replica and sends it to the new member over 1:1 Olm
    /// `SendControl` (server blind). The receiver upserts FILL-ONLY — it only fills the gaps
    /// and NEVER overwrites a live GP1 record (which is sender_id-verified). `room` is
    /// MANDATORY (group history only; the receiver verifies membership and `added_by`).
    /// `author`/`lamport` are self-attested (there is no cryptographic guarantee until D3b
    /// Ed25519; the exposure is bounded by fill-only + added_by gating + including
    /// tombstones — Fable review).
    PluginRecordSnapshot {
        room: String,
        records: Vec<SnapshotRecord>,
    },
    /// GP3 PULL trigger: a new member (or a member with incomplete history) REQUESTS a
    /// group's plugin data. `room` is mandatory. The receiver (`added_by`) verifies the
    /// sender's MEMBERSHIP → and sends it a `PluginRecordSnapshot`. Pull is more ROBUST than
    /// push: it is not one-shot (it repeats on every plugin open, and fill-only makes it
    /// idempotent) and it SELF-HEALS the added_by-offline and
    /// "I was already a member but never received the history" scenarios.
    /// Invisible control (NO UI row) — the `SendControl` pattern.
    PluginSnapshotRequest {
        room: String,
    },
    /// PULL trigger (Fable HIGH-2, late joiner): a new/incomplete member REQUESTS a group's
    /// installed PLUGINS (the code). `room` is mandatory. The receiver (an admin) verifies
    /// the sender's MEMBERSHIP → and fans out all active plugins of that room via
    /// `PluginInstall{room}` (the receiver then verifies the admin role). A push at assign time
    /// only reaches the member list of that moment; PULL is idempotent on every picker open and
    /// so covers the late joiner. Invisible control (NO UI row) — the twin of
    /// `PluginSnapshotRequest`.
    PluginInstallRequest {
        room: String,
    },
    /// Group plugin REMOVAL (admin "Remove from group"). When an ADMIN deletes a plugin from
    /// a group it sends this to the REMAINING members (plus its own sibling devices) → the
    /// receiver deletes its local `installed_plugins` record (forward secrecy: a removed
    /// plugin disappears EVERYWHERE, not just on the admin's device). Invisible
    /// control (NO UI message row). INBOUND GATE (fail-closed): accepted only from a ROOM
    /// ADMIN or from MY OWN sibling (a malicious member cannot delete somebody else's
    /// plugin). Twin of the `PluginInstall`/`PluginEpochKeyShare` admin-gate pattern. The
    /// DATA (`plugin_records`) is left UNTOUCHED — if the plugin is added again the history
    /// becomes visible (an assign-time decision). An older client sees `Unknown` (forward
    /// compatibility).
    PluginRemoved {
        room: String,
        plugin_id: String,
    },
    /// Server-log epoch key share (Faz-4 A; `PLUGIN_FEED_LOG_SPEC.md §2`).
    /// The SHARED AEAD key per (room,plugin,epoch) (256-bit, base64). An ADMIN generates it
    /// (at assign time, epoch 0) → and distributes it to active members over 1:1 Olm and to
    /// its own siblings as a self-copy. The receiver writes `key_epoch`+`key_b64` into
    /// `plugin_epoch_keys` → it can now decrypt that epoch's log entries with `open_entry`.
    /// Invisible control (NO UI row).
    /// INBOUND GATE: accepted only from a ROOM ADMIN or from MY OWN sibling (anything else is
    /// rejected). An older client falls back to `Unknown` (forward compatibility). `epoch` is
    /// i64 (matching the worker's key_epoch).
    PluginEpochKeyShare {
        room: String,
        plugin: String,
        epoch: i64,
        key_b64: String,
    },
    /// Self-copy (M2-S3.1): a separate Olm envelope of a 1:1 message going from device A to
    /// a peer, addressed to the sender's OWN other active devices (active_ids(my_user) MINUS
    /// my_device). My own receiving device catches it in the early branch → and writes it
    /// into the REAL `peer_id` conversation with `direction=Out` (right-aligned, "I sent
    /// this"). NOT invisible: it does produce a UI message row, but it never goes to the peer
    /// (it only syncs between my own devices).
    ///
    /// `peer_id` = the message's ACTUAL recipient (the conversation); the receiving device
    /// bases its direction+conversation decision entirely on this (there is NO
    /// recipient_device_id on the wire). `sent_at_ms` = the sender's reduce moment
    /// (cross-device chronological ordering). `origin_local_id` = the sender's Out-row
    /// `local_id` → dedup on the receiver via `oc-{origin_local_id}` (swallows
    /// double-display/replay).
    ///
    /// `payload` = the message WHOLE, as it went to the peer: its content, its thread and its
    /// `ext` (the forwarded flag, a caption…), which the receiver stores as is (Box is required
    /// for recursion). Its `inner` is whitelisted (Text/File/FileGroup/RichText/HtmlMessage/
    /// Location/LinkPreview) — a nested OutboundCopy/Activity/Plugin* is REJECTED by the receiver
    /// (B8 nested-REJECT). Until 2026-10-06 this carried the bare content and the sibling rebuilt
    /// a payload around it with no thread and no `ext`.
    OutboundCopy {
        peer_id: String,
        sent_at_ms: i64,
        origin_local_id: String,
        payload: Box<ChatPayload>,
    },
    /// G3 (group multi-device): a PLAINTEXT copy of a group message I sent myself, addressed
    /// to my sibling devices. The worker's group fan-out EXCLUDES my own account
    /// (`gm.user_id != sender`) → my sibling NEVER receives my group Megolm ciphertext → so a
    /// self-Olm plaintext copy is REQUIRED for it to see the group messages of its own
    /// account (the group twin of the 1:1 `OutboundCopy`). DIFFERENCES: `room_id` (the
    /// receiver writes into the GROUP conversation with peer_id=room_id) + `origin_local_id`
    /// (= the sender's Out-row `local_id` → on the receiver the row gets `local_id` = it → M4
    /// catch-up carries the SAME local_id → `find_by_local_id` dedups NATURALLY; no double
    /// bubble).
    ///
    /// It travels over self-Olm (`SendSelfState`) → Olm authenticates the sending device
    /// (UNSIGNED → a SECONDARY device can also produce a self-copy; this is NOT the
    /// primary-signed `DeviceStatePacket` → so G3 works in both directions, B1→B2 and
    /// B2→B1). The receiving sibling writes a group row with `direction=Out` ("I sent this",
    /// right-aligned). Fail-closed: only when sender==my_user. `payload.inner` is whitelisted
    /// (Text/File/FileGroup/RichText/HtmlMessage/Location/LinkPreview/P2pBlobOffer); a nested
    /// OutboundCopy or control message is REJECTED.
    ///
    /// ⚠️ FIELD NAMES: `ChatPayload` applies `#[serde(flatten)]` to `inner` → so this
    /// variant's fields CANNOT share a name with ChatPayload's own fields
    /// (`thread_id`/`thread_title`/`msg_uid`/`ext`); otherwise the outer field shadows the inner
    /// one during deserialization → "missing field". Hence `origin_local_id` (not msg_uid), and
    /// the copied message rides under `payload` with its own thread and `ext` inside it.
    GroupOutboundCopy {
        room_id: String,
        /// The sender's Out-row `local_id` (= the row local_id on the receiver → M4 dedup).
        /// Named `origin_local_id` so it does not clash with ChatPayload.msg_uid (the 1:1
        /// OutboundCopy pattern).
        origin_local_id: String,
        /// The sender's reduce moment (cross-device chronological ordering; 0 → the receiver
        /// substitutes now_ms).
        sent_at_ms: i64,
        /// The group message WHOLE, as the sender's own row holds it — content, thread and
        /// `ext` (a caption, an album slot, voice data). Until 2026-10-06 this was the bare
        /// content plus the thread, and my other devices showed my group photos with no caption.
        payload: Box<ChatPayload>,
    },
    /// History-sync packet at link time (M2-S3 / M4 — so that a new device does not come up
    /// empty, "like WhatsApp"). The primary device sends the ENTIRE history of this server
    /// (1:1 + group message rows — all of them already DECRYPTED PLAINTEXT locally) plus the
    /// peer/room/member metadata to the newly linked device through its OWN other active
    /// devices (self-Olm fan-out). Megolm session state and the Olm ratchet are NOT carried
    /// (only decrypted rows; future group messages are handled separately in S3.3). Invisible
    /// control (NO UI row) — the early branch in `inbound.rs` delegates to `inbound_state.rs`.
    ///
    /// **Root of trust (fail-closed):** `payload_b64` = base64 of the signed canonical body
    /// (`StatePacketBody` JSON); `sig_b64` = a signature over EXACTLY those bytes with the
    /// primary's Ed25519 (identical to the device-list JWS model). The receiver verifies it
    /// against the `primary` ed_pub of the signed list in its OWN `device_store` → on
    /// FAILURE the whole packet is rejected (no new root of trust is stored; the same root as
    /// `verify_device_list`). Olm already authenticates the sender's identity; the signature
    /// binds primary authority. transfer_id/part/total live INSIDE the signed body (so the
    /// server cannot tamper with them → no need to carry them on the outside). An old-APK
    /// receiver falls back to `Unknown` (forward compatibility).
    DeviceStatePacket {
        payload_b64: String,
        sig_b64: String,
    },
    /// History-sync REQUEST at link time (M4 PULL — race-free). Once finalize + attach + OTK
    /// publication are COMPLETE, the newly linked device sends this (over 1:1 Olm
    /// `SendControl` to active_ids[0] = the primary among its own devices) → the primary
    /// packages the history and answers with `DeviceStatePacket`(s) (`SendSelfState`). PULL
    /// instead of PUSH: the primary could not encrypt to the new device before it had
    /// published OTKs (a race); the request arrives once the REQUESTER is ready. Invisible
    /// control (NO UI row) — the twin of the PluginSnapshotRequest PULL pattern. Old APK →
    /// `Unknown` (forward compatibility). `since_ms` = incremental sync later on
    /// (v1: None = the whole history).
    ///
    /// `request_id` (#22 hard block): a correlation NONCE generated by the new device at link
    /// time. The primary echoes it VERBATIM into the reply's `StatePacketBody.request_id` →
    /// the new device declares "first history sync complete" ONLY on the LAST chunk of that
    /// id (until then the pairing stays provisional). `None` = catch-up (#18) / Part-A
    /// forward / old APK → outside the gate (the existing behavior). An old-APK primary
    /// ignores the field; an old-APK new device sends None → the hard block is off (backward
    /// compatibility). It lives inside Olm + the signature → the server cannot tamper with it.
    DeviceStateRequest {
        #[serde(default, skip_serializing_if = "Option::is_none")]
        since_ms: Option<i64>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        request_id: Option<String>,
    },
    /// Layer-4c receiver-side READ-state sibling sync. When INCOMING message(s) are read on
    /// one device, I tell MY OWN other devices (`SendSelfState`, recipient=my_user) "I read
    /// these `msg_uid`s from that peer" → the sibling marks `viewed_at` LOCALLY (`apply` is
    /// silent; NO receipt is re-sent to the peer → no receipt loop). `msg_uid` = the sender's
    /// `local_id` — stable and IDENTICAL across siblings (the per-device `remote_id` DIFFERS,
    /// so it cannot be used for matching). `peer_id` = the sending user in a 1:1.
    /// Invisible control (NO UI row). FAIL-CLOSED: accepted only when `sender == my_user`
    /// (inbound.rs); if a peer or a malicious server produces one it CANNOT touch my read
    /// state. Old APK → `Unknown` (forward compatibility; the skew is harmless — the sibling
    /// catches up on the next read or via M4).
    ReadSelfSync {
        peer_id: String,
        msg_uids: Vec<String>,
    },
    /// "Delete for everyone" sibling sync (the delete epic's Layer-4c twin). When a device
    /// deletes a message (the sender doing "delete for everyone" OR a local delete, or the
    /// receiver applying the sender's delete control), I tell MY OWN other devices
    /// (`SendSelfState`, recipient=my_user) "delete that message of that peer" → the sibling
    /// soft-deletes it LOCALLY (the twin of `ReadSelfSync`; nothing is re-sent to the peer →
    /// no loop). Invisible control (NO UI row). FAIL-CLOSED: accepted only when
    /// `sender == my_user` (inbound.rs); if a peer or a malicious server produces one it
    /// cannot delete my messages. Old APK → `Unknown` (forward compatibility; the sibling
    /// converges on the next M4/redelivery).
    ///
    /// ⚠️ FIELD NAME: `origin_local_id` = the sender's stable `local_id` (the correlation key
    /// that is IDENTICAL across siblings; conceptually the `msg_uid`). It CANNOT BE NAMED
    /// `msg_uid` — `ChatPayload` applies `#[serde(flatten)]` to `inner` and the
    /// `ChatPayload.msg_uid` field already EXISTS → an identical name shadows the inner field
    /// → "missing field" (this is also why GroupOutboundCopy/OutboundCopy use
    /// `origin_local_id`). `peer_id` = the other user in a 1:1, or the room_id in a group
    /// (not present in ChatPayload → no clash).
    DeleteSelfSync {
        peer_id: String,
        origin_local_id: String,
    },
    /// "Get it from there": a file I sent over P2P that THIS device does not hold, asked of my
    /// other devices (`SendSelfState` to all of them). A copy of such a file is never pulled
    /// by itself (Hasan, 2026-10-15); a tap sends this, and whichever device of mine is running
    /// and holds the bytes seeds them and answers with [`InnerMessage::OwnFileOffer`] to the
    /// asking device alone. `origin_local_id` is the message's id on the device that sent it (a
    /// group row has that id everywhere; a 1:1 copy is `oc-{origin_local_id}`), `peer_id` the
    /// contact or the room. Invisible control. FAIL-CLOSED: answered only when
    /// `sender == my_user`. Old APK → `Unknown`, and the asking device's wait ends unanswered.
    OwnFileRequest {
        peer_id: String,
        origin_local_id: String,
    },
    /// The answer to [`InnerMessage::OwnFileRequest`]: where to pull my own file from right now.
    /// The ticket names a blob the answering device seeds for this pull, and the manifest is the
    /// key that blob was encrypted with — a fresh one when the original offer was no longer
    /// seeded. Invisible control, accepted only from my own user.
    OwnFileOffer {
        peer_id: String,
        origin_local_id: String,
        ticket: String,
        manifest: FileManifest,
        /// How long the answering device keeps that blob seeded from the moment it answered, when
        /// it knows (a fresh seed). An answer read after that — it waited at the relay while the
        /// asker was off — names a dead blob, and the asker asks again.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        seeded_for_ms: Option<i64>,
    },
    /// Profile photo declaration (Profile-Photo epic §2.1 — E2E avatar pointer;
    /// docs/PROFIL_FOTOGRAF_EPIC_2026_07_16.md). The photo ITSELF is not carried on the
    /// wire: what is carried is the ref of the ENCRYPTED blob on the worker + the blob key +
    /// the expected sha256 of the plaintext content (the server stays blind).
    ///
    /// SECURITY CONTRACT:
    /// - There is NO IDENTITY in the payload — the receiver writes the avatar ONLY against
    ///   the identity of the Olm sender (the whole class of "set somebody else's photo" is
    ///   impossible).
    /// - `rev` is MONOTONIC per sender — an older/equal rev is silently ignored by the
    ///   receiver (replay/rollback protection; avatar_store).
    /// - `avatar_ref=None` = "I removed my photo" (a tombstone; rev still increments).
    /// - Invisible control (NO UI row). Old APK → `Unknown` (forward compatibility).
    /// - The group twin `RoomAvatar` arrives in Faz D (together with the room-avatar store;
    ///   it will require receiver-side owner/admin role verification).
    ProfileAvatar {
        rev: u64,
        #[serde(skip_serializing_if = "Option::is_none", default)]
        avatar_ref: Option<String>,
        #[serde(skip_serializing_if = "Option::is_none", default)]
        key_b64: Option<String>,
        #[serde(skip_serializing_if = "Option::is_none", default)]
        sha256_hex: Option<String>,
        #[serde(skip_serializing_if = "Option::is_none", default)]
        bytes: Option<u32>,
        #[serde(skip_serializing_if = "Option::is_none", default)]
        mime: Option<String>,
    },
    /// A group-library item shared into the room's chat: a card that opens the item, never the
    /// file ([`LibraryCardRef`]). Group-only, over Megolm. A build that predates it decodes it as
    /// `Unknown` below, which the chat and the list show as "Unsupported message".
    LibraryCard(LibraryCardRef),
    /// A member's message in a room, copied 1:1 to a bot of that room that it called (named in
    /// `ext.mentions`, or `/command`). Only a bot ever receives it; a human kernel drops one
    /// ([`InnerMessage::is_bot_bound`], `crate::bots`). Phase 3 sends it; it is declared now so
    /// every human build already refuses it. `docs/BOTS_BUILD.md` §2.6.
    BotCall {
        room_id: String,
        msg_uid: String,
        body: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        lang: Option<String>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        utc_offset_min: Option<i32>,
    },
    /// A tap on a bot's button, sent to that bot alone (Phase 4). Bot-bound like `BotCall`.
    BotTap {
        #[serde(default, skip_serializing_if = "Option::is_none")]
        room_id: Option<String>,
        msg_uid: String,
        action_id: String,
    },
    /// Forward-compatibility catch-all — messages carrying an unknown `kind` tag land here.
    /// Thanks to `#[serde(other)]` the payload of any unrecognized tag is silently
    /// swallowed; the decrypt chain does not collapse.
    ///
    /// If `kind == "unknown"` shows up in the UI, it is rendered as a note along the lines
    /// of "unknown message type, please update the app" and the message is acked (so it does
    /// not pile up in server retries).
    ///
    /// Never PRODUCE this variant for `encode`/encryption — it is only used when decoding
    /// incoming messages. If you produce it on the encode side, serde writes
    /// `"kind":"unknown"` into the payload and the other side lands in the same catch-all (a
    /// pointless ping-pong).
    #[serde(other)]
    Unknown,
}

/// GP3 snapshot record — the wire projection of `PluginRecordRow` (EXCLUDING
/// `server_id`/`updated_at`; the receiver writes those with `now` on its own server).
/// `author_id`/`lamport` come from the adding member's replica (self-attested — bounded by
